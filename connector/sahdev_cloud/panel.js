(() => {
  'use strict';
  document.querySelectorAll('[data-cloud-panel]').forEach(panel => {
    if (panel.dataset.bound) return;
    panel.dataset.bound = 'true';
    const form = panel.querySelector('form'), status = panel.querySelector('[data-status]'), result = panel.querySelector('[data-result]');
    const submit = form.querySelector('[type=submit]'), retry = form.querySelector('[data-check-result]');
    let currentId = null, pendingBody = null, timer = null, polls = 0;
    const post = async data => {
      const response = await fetch(panel.dataset.endpoint, {method:'POST', credentials:'same-origin', headers:{'Content-Type':'application/json'}, body:JSON.stringify({...data, csrf:panel.dataset.csrf, ticket_id:Number(panel.dataset.ticket)})});
      const body = await response.json();
      if (!response.ok) { const error = new Error(body.error || 'Cloud request failed.'); error.status = response.status; throw error; }
      return body;
    };
    form.querySelector('[data-load-models]').addEventListener('click', async () => {
      try {
        status.textContent = 'Loading allowed cloud models…';
        const body = await post({action:'models'}), select = form.elements.model_id;
        select.replaceChildren();
        body.models.forEach(model => { const option = document.createElement('option'); option.value = model.id; option.textContent = model.name; select.append(option); });
        status.textContent = body.models.length ? 'Models loaded. Requests consume your brand’s credits.' : 'No models are assigned to this plan.';
      } catch (error) { status.textContent = error.message; }
    });
    const display = body => {
      result.replaceChildren();
      if (!body.output) { result.textContent = 'Response unavailable or expired. Check the usage record before making another request.'; return; }
      if (body.output.format === 'invalid') { result.textContent = body.output.message; return; }
      const content = body.output.format === 'fields' ? body.output.fields : {Response:body.output.content};
      Object.entries(content).forEach(([name, value]) => {
        const section = document.createElement('section'), title = document.createElement('h4'), text = document.createElement('div');
        title.textContent = name.replaceAll('_',' ');
        // HTML is generated by the cloud Markdown renderer from a validated output; no model HTML is accepted.
        text.innerHTML = body.output.format === 'fields' ? body.output.html[name] : body.output.html;
        section.append(title,text);
        if (['CLIENT_REPLY','TEMPLATE','Response'].includes(name)) {
          const button = document.createElement('button'); button.type = 'button'; button.textContent = 'Copy draft';
          button.addEventListener('click', async () => { try { await navigator.clipboard.writeText(String(value)); status.textContent = 'Draft copied. Review it before sending.'; } catch { status.textContent = 'Select the draft text to copy it.'; } });
          section.append(button);
        }
        result.append(section);
      });
      const links = document.createElement('nav'); links.setAttribute('aria-label','Related WHMCS records');
      const routes = {ticket:['supporttickets.php','id','view'],client:['clientssummary.php','userid'],invoice:['invoices.php','id','edit'],service:['clientsservices.php','id']};
      (body.record_links || []).forEach(record => {
        const route = routes[record.type]; if (!route || !Number.isSafeInteger(record.id) || record.id < 1) return;
        const url = new URL(route[0],window.location.href); url.searchParams.set(route[1],String(record.id));
        if (route[2]) url.searchParams.set('action',route[2]);
        const link = document.createElement('a'); link.href = url.href; link.textContent = record.label; link.target = '_blank'; link.rel = 'noopener'; links.append(link);
      });
      if (links.childElementCount) result.append(links);
    };
    const check = async () => {
      clearTimeout(timer);
      try {
        if (!currentId && pendingBody) { const accepted = await post(pendingBody); currentId = accepted.id; }
        if (!currentId) return;
        const body = await post({action:'result',id:currentId});
        status.textContent = 'Request '+body.state+'. Reference: '+currentId;
        if (body.state === 'settled' || body.state === 'released') {
          submit.disabled = false; retry.hidden = true; pendingBody = null;
          if (body.state === 'settled') { display(body); status.textContent += ' Charged '+(body.charged_credits/body.credit_scale).toFixed(6)+' credits.'; }
          else result.textContent = 'No response was delivered. Credits were released. Check the cloud configuration.';
        } else if (body.state === 'uncertain') { retry.hidden = false; status.textContent += ' The provider outcome needs operator review. No new request was started.'; }
        else if (++polls < 60) timer = setTimeout(check,2500);
        else { retry.hidden = false; status.textContent += ' Still waiting. Use Check request to resume.'; }
      } catch (error) {
        if (!currentId && [400,401,402,403,404,419,422,423,429].includes(error.status)) {
          submit.disabled = false; retry.hidden = true; pendingBody = null; status.textContent = error.message+' Correct the settings and submit again.';
        } else { retry.hidden = false; status.textContent = error.message+' Use Check request to resume the same operation.'; }
      }
    };
    form.addEventListener('submit', event => {
      event.preventDefault(); if (submit.disabled) return;
      pendingBody = {action:'submit',...Object.fromEntries(new FormData(form))}; pendingBody.max_output_tokens = Number(pendingBody.max_output_tokens);
      currentId = null; polls = 0; submit.disabled = true; retry.hidden = true; result.replaceChildren(); status.textContent = 'Submitting cloud workflow…'; check();
    });
    retry.addEventListener('click',() => { polls = 0; check(); });
    window.addEventListener('pagehide',() => clearTimeout(timer),{once:true});
  });
})();
