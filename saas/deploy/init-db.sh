#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username postgres --dbname postgres --set=app_password="$SAHDEV_DB_PASSWORD" <<'SQL'
CREATE ROLE sahdev LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT PASSWORD :'app_password';
CREATE DATABASE sahdev OWNER sahdev;
REVOKE ALL ON DATABASE sahdev FROM PUBLIC;
GRANT CONNECT ON DATABASE sahdev TO sahdev;
REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;
REVOKE CONNECT ON DATABASE template1 FROM PUBLIC;
SQL
